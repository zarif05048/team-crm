-- Owner-editable bot rules & knowledge (owner, 1 Nov 2026).
--
-- The bots' rules and clinic facts used to live only in code (the fleet's
-- ai.js and src/lib/ai/knowledge.ts), so changing what a bot says needed a
-- developer and a deploy. These rows are read live by every bot — the three
-- WhatsApp lines every few minutes and the web chat on each reply — and sit
-- at the END of their instructions, where they win over anything above them.
-- The owner's personal agent (Hermes) edits them with the CRM key it already
-- holds; nobody else can, because RLS is on and there are no policies — only
-- the service/secret key reads or writes this table.
--
--   kind   'rule' (how to behave) or 'knowledge' (a clinic fact)
--   scope  which bots read it: all · whatsapp (the three WhatsApp lines) ·
--          webchat (website / Google chat, both clinics) · marketing (the
--          promotions line) · dungun / paka (that clinic's WhatsApp line AND
--          its web chat)
--   active false keeps the row but takes it out of every bot
--
-- Every insert, edit and delete is copied to bot_rules_log by a trigger, with
-- the row before and after and who said they changed it (updated_by), so a
-- rule that reached patients can always be traced and put back.

create table if not exists public.bot_rules (
  id bigint generated by default as identity primary key,
  kind text not null default 'rule' check (kind in ('rule', 'knowledge')),
  scope text not null default 'all'
    check (scope in ('all', 'whatsapp', 'dungun', 'paka', 'marketing', 'webchat')),
  title text not null default '' check (length(title) <= 120),
  body text not null check (length(btrim(body)) between 1 and 3000),
  priority integer not null default 100,
  active boolean not null default true,
  updated_by text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.bot_rules enable row level security;
create index if not exists bot_rules_active_idx on public.bot_rules (active, scope, priority);

create table if not exists public.bot_rules_log (
  id bigint generated by default as identity primary key,
  rule_id bigint,
  action text not null,
  before jsonb,
  after jsonb,
  changed_by text not null default '',
  changed_at timestamptz not null default now()
);
alter table public.bot_rules_log enable row level security;
create index if not exists bot_rules_log_rule_idx on public.bot_rules_log (rule_id, changed_at desc);

create or replace function public.bot_rules_audit() returns trigger
language plpgsql set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    insert into public.bot_rules_log (rule_id, action, before, changed_by)
      values (old.id, 'delete', to_jsonb(old), old.updated_by);
    return old;
  end if;
  new.updated_at := now();
  insert into public.bot_rules_log (rule_id, action, before, after, changed_by)
    values (new.id, lower(tg_op), case when tg_op = 'UPDATE' then to_jsonb(old) end, to_jsonb(new), new.updated_by);
  return new;
end $$;

drop trigger if exists bot_rules_audit on public.bot_rules;
create trigger bot_rules_audit before insert or update or delete on public.bot_rules
  for each row execute function public.bot_rules_audit();
